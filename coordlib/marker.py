"""The machine marker that makes a GitHub comment a coord record.

Every agent posts as the same login (alex-bridges), so the comment author says
nothing about which agent wrote it. The marker does:

    <!-- coord:v1 {"agent":"claude@Eidolon:agent-coord","issue":980,"kind":"claim",...} -->

Rules:
- It is the LAST non-blank line of the comment, ignoring a trailing Claude Code
  footer ("---" + "_Generated by [Claude Code](…)_", which cloud sessions append). A
  quote-reply copies an earlier marker into the middle of a new comment; only the last
  line counts, so a quote never impersonates its source. (Kept from PR #989's design.)
- The payload is JSON, so file lists and free text need no escaping rules of
  our own. "--" is written as "-\\u002d" so the payload can never close the
  HTML comment early; in valid JSON text "--" can only occur inside a string,
  where the escape decodes back to the same characters.
"""

from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Optional

PREFIX = "<!-- coord:v1 "
SUFFIX = " -->"

KINDS = ("claim", "release", "msg", "train-add", "train-remove", "train", "review-substitute", "alex-approve",
         "outage", "conductor")


def encode(payload: Dict[str, Any]) -> str:
    text = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    while "--" in text:
        text = text.replace("--", "-\\u002d")
    return f"{PREFIX}{text}{SUFFIX}"


# The footer a posting tool appends AFTER the marker. Claude cloud sessions add
# "---" + "_Generated by [Claude Code](https://claude.ai/code)_" to every comment they
# post (stress test, 2026-09-25): with the marker no longer last, every cloud claim,
# message and train-add was invisible. A trailing block is skipped only when it contains
# that "_Generated by" line (a lone "---" is not a footer), and nothing else is skipped,
# so a quoted marker ("> <!-- coord:v1 …") in the middle of a comment still never counts.
_GENERATED = re.compile(r"^_Generated by \[Claude Code\]\([^)]*\)_$")
_RULE = re.compile(r"^-{3,}$")


def _marker_index(lines: List[str]) -> int:
    """Index of the last line that is neither blank nor part of a trailing tool footer."""
    index = len(lines) - 1
    while index >= 0 and not lines[index].strip():
        index -= 1
    probe = index
    saw_generated = False
    while probe >= 0 and (not lines[probe].strip() or _GENERATED.match(lines[probe].strip())
                          or _RULE.match(lines[probe].strip())):
        saw_generated = saw_generated or bool(_GENERATED.match(lines[probe].strip()))
        probe -= 1
    return probe if saw_generated else index


def decode(body: Optional[str]) -> Optional[Dict[str, Any]]:
    """The payload of a comment whose last non-blank line (before any tool footer) is a marker."""
    if not body:
        return None
    lines = [line.strip() for line in body.replace("\r\n", "\n").split("\n")]
    index = _marker_index(lines)
    if index < 0:
        return None
    last = lines[index]
    if not (last.startswith(PREFIX) and last.endswith(SUFFIX)):
        return None
    raw = last[len(PREFIX): -len(SUFFIX)]
    try:
        payload = json.loads(raw)
    except ValueError:
        return None
    if not isinstance(payload, dict) or payload.get("kind") not in KINDS:
        return None
    return payload


def recipients(payload: Dict[str, Any]) -> List[str]:
    """The addresses a record is sent to (see identity.matches): a `send` message's `to`,
    and the same field on any other record that notifies someone, such as the train's
    `held` notice (#1034). `inbox` delivers a record by this, whatever its kind."""
    to = payload.get("to")
    return [str(address) for address in to] if isinstance(to, list) else []


def compose(text: str, payload: Dict[str, Any]) -> str:
    """A comment body: the human-readable text, a blank line, then the marker."""
    return f"{text.rstrip()}\n\n{encode(payload)}\n"


def strip(body: str) -> str:
    """The human-readable part of a coord comment (the marker line and any footer after it removed)."""
    lines = body.replace("\r\n", "\n").split("\n")
    index = _marker_index(lines)
    if index >= 0 and decode(lines[index]) is not None:
        lines = lines[:index]
    return "\n".join(lines).strip()
